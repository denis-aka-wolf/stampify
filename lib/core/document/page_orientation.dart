// Определяет ориентацию страницы документа Stampify.
//
// Ориентация влияет на итоговые физические ширину и высоту страницы,
// но не изменяет сам формат бумаги.

/// Ориентация страницы документа.
enum PageOrientation {
  /// Вертикальная ориентация страницы.
  portrait,

  /// Горизонтальная ориентация страницы.
  landscape,
}