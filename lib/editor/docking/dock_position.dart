// Определяет стороны редактора, к которым могут быть
// прикреплены docking-группы.
//
// Используется моделью docking-интерфейса для определения
// расположения группы панелей.

/// Положение docking-группы относительно рабочей области.
enum DockPosition {
  /// Левая сторона рабочей области.
  left,

  /// Правая сторона рабочей области.
  right,

  /// Верхняя сторона рабочей области.
  top,

  /// Нижняя сторона рабочей области.
  bottom,
}